//! ST / Campaign import-export compatibility matrix helpers.
//!
//! Distinguishes intentional normalization from data loss during:
//! import → internal → export/serialize → re-import.

use serde::{Deserialize, Serialize};
use serde_json::Value;
use storyforge_domain::character::{Character, StCharacterData};
use storyforge_domain::preset::RegexScript;
use storyforge_domain::variables::extract_mvu_schema_from_extensions;
use storyforge_domain::world_info::WorldInfoBook;

/// Severity of a compatibility observation.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum CompatSeverity {
    /// Confirmed data loss / corruption risk that must be fixed or documented.
    Loss,
    /// Wire-level representation change with no declared equivalence mapping
    /// (for example a `position` value that maps to no known code). A hard
    /// finding: it is counted by [`CompatReport::has_losses`].
    WireDrift,
    /// Wire-level representation change whose values are equivalent under an
    /// explicit mapping declared in code (see [`POSITION_WIRE_MAPPING`]).
    /// Recorded with `before`/`after` evidence — never a blanket "intentional".
    Normalized,
    /// Intentional StoryForge normalization (not treated as a bug).
    Intentional,
    /// Unknown / opaque field survived as opaque payload.
    Preserved,
    /// Input rejected fail-closed without store mutation.
    Rejected,
}

/// One row in the machine-readable compatibility matrix.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CompatFinding {
    pub area: String,
    pub field_path: String,
    pub severity: CompatSeverity,
    pub detail: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub before: Option<Value>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub after: Option<Value>,
}

/// High-level classification assigned to a whole matrix row (fixture/case).
///
/// Maps to the five categories required by the import-fixture-corpus plan:
/// preserved, normalized-intentionally, unsupported, lossy-bug, not-applicable.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RowClassification {
    Preserved,
    NormalizedIntentionally,
    Unsupported,
    LossyBug,
    NotApplicable,
}

/// Whether a matrix row's evidence is complete enough to publish.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RowCompleteness {
    Complete,
    Incomplete,
}

/// A single reproducible row in the compatibility matrix.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MatrixRow {
    pub fixture_id: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub seed: Option<u64>,
    pub classification: RowClassification,
    pub completeness: RowCompleteness,
}

/// Aggregate report generated by tests or scripts.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CompatReport {
    pub format_version: u32,
    /// Monotonic schema version for the *matrix* payload (rows + summary),
    /// bumped when the row schema changes. Distinct from `format_version`
    /// (the JSON envelope version) so consumers can evolve independently.
    pub matrix_version: u32,
    pub generated_by: String,
    pub seed: Option<u64>,
    pub findings: Vec<CompatFinding>,
    pub summary: CompatSummary,
    #[serde(default)]
    pub rows: Vec<MatrixRow>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CompatSummary {
    pub loss: usize,
    /// Wire-contract drifts with no declared equivalence mapping.
    #[serde(default)]
    pub wire_drift: usize,
    /// Representation changes that are equivalent under a mapping declared in
    /// code, recorded with `before`/`after` evidence.
    #[serde(default)]
    pub normalized: usize,
    pub intentional: usize,
    pub preserved: usize,
    pub rejected: usize,
}

impl CompatReport {
    pub const FORMAT_VERSION: u32 = 1;
    /// Current matrix row schema version.
    ///
    /// Bumped 1 → 2 when the report payload gained the `wire_drift` /
    /// `normalized` severity values and summary counters (M-06 wire leg).
    pub const MATRIX_VERSION: u32 = 2;

    pub fn new(generated_by: impl Into<String>, seed: Option<u64>) -> Self {
        Self {
            format_version: Self::FORMAT_VERSION,
            matrix_version: Self::MATRIX_VERSION,
            generated_by: generated_by.into(),
            seed,
            findings: Vec::new(),
            summary: CompatSummary {
                loss: 0,
                wire_drift: 0,
                normalized: 0,
                intentional: 0,
                preserved: 0,
                rejected: 0,
            },
            rows: Vec::new(),
        }
    }

    pub fn push(&mut self, finding: CompatFinding) {
        match finding.severity {
            CompatSeverity::Loss => self.summary.loss += 1,
            CompatSeverity::WireDrift => self.summary.wire_drift += 1,
            CompatSeverity::Normalized => self.summary.normalized += 1,
            CompatSeverity::Intentional => self.summary.intentional += 1,
            CompatSeverity::Preserved => self.summary.preserved += 1,
            CompatSeverity::Rejected => self.summary.rejected += 1,
        }
        self.findings.push(finding);
    }

    /// Register a reproducible matrix row (fixture id + seed + classification).
    pub fn register_row(&mut self, row: MatrixRow) {
        self.rows.push(row);
    }

    /// Fail closed unless the registered matrix rows form a unique exact set
    /// equal to `expected`, with every row marked `Complete`.
    ///
    /// Rules (all must hold):
    /// 1. No duplicate `fixture_id` (a Complete row cannot mask a later Incomplete).
    /// 2. No Incomplete rows at all.
    /// 3. The set of registered ids equals the expected set exactly
    ///    (missing *or* unexpected extras both fail).
    pub fn assert_matrix_complete(&self, expected: &[&str]) -> Result<(), String> {
        use std::collections::{BTreeMap, BTreeSet};

        let mut counts: BTreeMap<&str, usize> = BTreeMap::new();
        for row in &self.rows {
            *counts.entry(row.fixture_id.as_str()).or_insert(0) += 1;
            if row.completeness == RowCompleteness::Incomplete {
                return Err(format!(
                    "matrix incomplete: row '{}' is marked incomplete",
                    row.fixture_id
                ));
            }
        }
        for (id, count) in &counts {
            if *count > 1 {
                return Err(format!(
                    "matrix incomplete: fixture_id '{id}' is registered {count} times (must be unique)"
                ));
            }
        }

        let expected_set: BTreeSet<&str> = expected.iter().copied().collect();
        let actual_set: BTreeSet<&str> = self.rows.iter().map(|r| r.fixture_id.as_str()).collect();
        if expected_set != actual_set {
            let missing: Vec<&str> = expected_set.difference(&actual_set).copied().collect();
            let extra: Vec<&str> = actual_set.difference(&expected_set).copied().collect();
            return Err(format!(
                "matrix incomplete: expected set mismatch; missing={missing:?} extra={extra:?}"
            ));
        }
        Ok(())
    }

    /// True when the report carries a hard defect: a `Loss` or a wire-level
    /// drift with no declared equivalence mapping (`WireDrift`).
    ///
    /// An explicit `Normalized` transition is *not* a hard defect, but it is
    /// still reported with `before`/`after` evidence so a wire contract change
    /// stays visible in the machine-readable report.
    pub fn has_losses(&self) -> bool {
        self.summary.loss > 0 || self.summary.wire_drift > 0
    }

    /// True when the report carries a wire-level representation change that no
    /// declared in-code mapping explains.
    pub fn has_wire_drift(&self) -> bool {
        self.summary.wire_drift > 0
    }

    pub fn to_json_pretty(&self) -> Result<String, serde_json::Error> {
        serde_json::to_string_pretty(self)
    }

    /// Render a stable Markdown summary of this report.
    ///
    /// Carries the matrix version, generator/seed, classified-finding counts,
    /// the registered matrix rows, and (if present) the loss / wire-drift /
    /// explicit-normalization / intentional findings. No raw card body is ever
    /// emitted: findings are summarized by area / field_path / severity /
    /// detail only (the `before`/`after` evidence lives in the JSON report).
    pub fn to_markdown(&self) -> String {
        let mut md = String::new();
        md.push_str(&format!(
            "# Compatibility Report\n\n- generated_by: `{}`\n- format_version: {}\n- matrix_version: {}\n",
            self.generated_by, self.format_version, self.matrix_version
        ));
        if let Some(seed) = self.seed {
            md.push_str(&format!("- seed: `0x{seed:08X}`\n"));
        }
        md.push_str("\n## Summary\n\n");
        md.push_str("| loss | wire_drift | normalized | intentional | preserved | rejected |\n");
        md.push_str("|------|------------|------------|-------------|-----------|----------|\n");
        md.push_str(&format!(
            "| {} | {} | {} | {} | {} | {} |\n",
            self.summary.loss,
            self.summary.wire_drift,
            self.summary.normalized,
            self.summary.intentional,
            self.summary.preserved,
            self.summary.rejected
        ));

        if !self.rows.is_empty() {
            md.push_str("\n## Matrix rows\n\n");
            md.push_str("| fixture_id | seed | classification | completeness |\n");
            md.push_str("|------------|------|----------------|--------------|\n");
            for row in &self.rows {
                let seed = row
                    .seed
                    .map(|s| format!("`0x{s:08X}`"))
                    .unwrap_or_else(|| "—".into());
                md.push_str(&format!(
                    "| {} | {} | {:?} | {:?} |\n",
                    row.fixture_id, seed, row.classification, row.completeness
                ));
            }
        }

        let losses: Vec<_> = self
            .findings
            .iter()
            .filter(|f| f.severity == CompatSeverity::Loss)
            .collect();
        if !losses.is_empty() {
            md.push_str("\n## Loss findings\n\n");
            md.push_str("| area | field_path | detail |\n");
            md.push_str("|------|-------------|--------|\n");
            for f in losses {
                md.push_str(&format!(
                    "| {} | {} | {} |\n",
                    f.area, f.field_path, f.detail
                ));
            }
        }

        let intentional: Vec<_> = self
            .findings
            .iter()
            .filter(|f| f.severity == CompatSeverity::Intentional)
            .collect();
        if !intentional.is_empty() {
            md.push_str("\n## Intentional normalizations\n\n");
            md.push_str("| area | field_path | detail |\n");
            md.push_str("|------|-------------|--------|\n");
            for f in intentional {
                md.push_str(&format!(
                    "| {} | {} | {} |\n",
                    f.area, f.field_path, f.detail
                ));
            }
        }

        let normalized: Vec<_> = self
            .findings
            .iter()
            .filter(|f| f.severity == CompatSeverity::Normalized)
            .collect();
        if !normalized.is_empty() {
            md.push_str("\n## Explicit normalizations (equivalence declared in code)\n\n");
            md.push_str("| area | field_path | detail |\n");
            md.push_str("|------|-------------|--------|\n");
            for f in normalized {
                md.push_str(&format!(
                    "| {} | {} | {} |\n",
                    f.area, f.field_path, f.detail
                ));
            }
        }

        let wire_drift: Vec<_> = self
            .findings
            .iter()
            .filter(|f| f.severity == CompatSeverity::WireDrift)
            .collect();
        if !wire_drift.is_empty() {
            md.push_str("\n## Wire drift findings\n\n");
            md.push_str("| area | field_path | detail |\n");
            md.push_str("|------|-------------|--------|\n");
            for f in wire_drift {
                md.push_str(&format!(
                    "| {} | {} | {} |\n",
                    f.area, f.field_path, f.detail
                ));
            }
        }

        md
    }
}

/// Compare two ST-shaped character data payloads for semantic round-trip fidelity.
///
/// Paths under `intentional_paths` are recorded as intentional normalization, not loss.
pub fn compare_st_data(
    before: &Value,
    after: &Value,
    intentional_paths: &[&str],
) -> Vec<CompatFinding> {
    let mut findings = Vec::new();
    compare_value(
        "st.data",
        "",
        before,
        after,
        intentional_paths,
        &mut findings,
    );
    findings
}

/// Compare the SOURCE ST card JSON against the FIRST import result.
///
/// This is a distinct comparison leg from `compare_character_roundtrip`:
/// round-trip compares import -> export -> reimport, which can mask losses
/// that already happened on the initial parse/normalize step. This helper
/// catches first-import losses independently of the later raw-JSON copy.
///
/// `source` is the original ST card JSON (its `.data` object), `imported` is
/// the first-imported Character, and `intentional_paths` lists fields that are
/// documented intentional normalizations (e.g. `key`, `keysecondary`).
///
/// Equivalent empty forms are treated as intentional: `[]` ↔ `null` for
/// `secondary_keys` (first import stores empty secondary keys as `None`).
pub fn compare_source_to_first_import(
    source: &Value,
    imported: &Character,
    intentional_paths: &[&str],
) -> CompatReport {
    let mut report = CompatReport::new("compare_source_to_first_import", None);
    let source_data = source.get("data").unwrap_or(source);
    let findings = compare_st_data(source_data, &imported.raw_card_json, intentional_paths);
    for finding in findings {
        report.push(reclassify_normalizations(finding));
    }
    report
}

/// Reclassify documented, evidence-free normalizations that are identical on
/// every wire-level comparison leg.
///
/// Empty `secondary_keys` (`[]` on the source card) is stored as `null`/`None`
/// on first import, so an `[] ↔ null` pair is an intentional normalization
/// rather than a loss.
fn reclassify_normalizations(finding: CompatFinding) -> CompatFinding {
    if finding.severity == CompatSeverity::Loss
        && finding.field_path.contains("secondary_keys")
        && is_empty_list_or_null(finding.before.as_ref())
        && is_empty_list_or_null(finding.after.as_ref())
    {
        return CompatFinding {
            area: finding.area,
            field_path: finding.field_path,
            severity: CompatSeverity::Intentional,
            detail: "empty secondary_keys [] normalized to null/None on first import".into(),
            before: finding.before,
            after: finding.after,
        };
    }
    finding
}

fn is_empty_list_or_null(value: Option<&Value>) -> bool {
    match value {
        None => true,
        Some(Value::Null) => true,
        Some(Value::Array(items)) => items.is_empty(),
        _ => false,
    }
}

/// Extract the ST card `data` object from a PNG produced by
/// [`crate::png::write_st_card_png`] — i.e. the exact wire bytes a third-party
/// ST tool reads out of the `chara` tEXt chunk.
pub fn exported_png_card_data(png_bytes: &[u8]) -> Result<Value, String> {
    let chunks =
        crate::png::parse_png(png_bytes).map_err(|e| format!("parse exported PNG: {e}"))?;
    let payload = chunks
        .iter()
        .find_map(|chunk| match chunk {
            crate::png::PngChunk::Text { keyword, text }
                if keyword.eq_ignore_ascii_case("chara") =>
            {
                Some(text.as_str())
            }
            _ => None,
        })
        .ok_or_else(|| "exported PNG has no chara tEXt chunk".to_string())?;
    let json_bytes = base64::Engine::decode(&base64::engine::general_purpose::STANDARD, payload)
        .map_err(|e| format!("decode exported chara payload: {e}"))?;
    let card: Value = serde_json::from_slice(crate::strip_utf8_bom(&json_bytes))
        .map_err(|e| format!("parse exported chara JSON: {e}"))?;
    Ok(card.get("data").cloned().unwrap_or(card))
}

/// Wire-level comparison leg: exported card JSON vs the SOURCE card JSON,
/// field by field.
///
/// This is a distinct leg from [`compare_source_to_first_import`] (source vs
/// first import) and [`compare_character_roundtrip`] (domain object → export →
/// domain object). Both of those compare *domain* values, so a wire-level
/// representation change — `position` written as a numeric code instead of the
/// ST string label, for example — is structurally invisible to them. This leg
/// compares the JSON that actually lands in the exported PNG/JSON card against
/// the JSON that came in, so wire drift is visible to CI.
///
/// `source` is the original ST card JSON (its `.data` object is used when
/// present); `exported_wire` is the exported card `data` object (see
/// [`exported_png_card_data`]).
pub fn compare_export_wire_to_source(source: &Value, exported_wire: &Value) -> CompatReport {
    let mut report = CompatReport::new("compare_export_wire_to_source", None);
    let source_data = source.get("data").unwrap_or(source);
    for finding in compare_st_data(source_data, exported_wire, INTENTIONAL_WIRE_PATHS) {
        report.push(reclassify_normalizations(finding));
    }
    report
}

/// Build a high-level inventory of fields StoryForge currently understands from a Character.
pub fn inventory_character(character: &Character) -> CompatReport {
    let mut report = CompatReport::new("inventory_character", None);

    for (path, present) in [
        ("name", !character.name.is_empty()),
        ("description", !character.description.is_empty()),
        ("personality", !character.personality.is_empty()),
        ("scenario", !character.scenario.is_empty()),
        ("first_mes", !character.first_mes.is_empty()),
        ("mes_example", !character.mes_example.is_empty()),
        ("system_prompt", !character.system_prompt.is_empty()),
        (
            "post_history_instructions",
            !character.post_history_instructions.is_empty(),
        ),
        ("tags", !character.tags.is_empty()),
        ("creator", !character.creator.is_empty()),
        ("character_version", !character.character_version.is_empty()),
        (
            "alternate_greetings",
            !character.alternate_greetings.is_empty(),
        ),
        ("extensions", !character.extensions.is_null()),
        ("raw_card_json", character.raw_card_json.is_object()),
        (
            "embedded_world_info",
            character.embedded_world_info.is_some(),
        ),
        ("renderable_assets", character.renderable_assets.is_some()),
    ] {
        if present {
            report.push(CompatFinding {
                area: "character".into(),
                field_path: path.into(),
                severity: CompatSeverity::Preserved,
                detail: "typed/internal field populated after import".into(),
                before: None,
                after: None,
            });
        }
    }

    if let Some(obj) = character.raw_card_json.as_object() {
        for key in obj.keys() {
            if matches!(
                key.as_str(),
                "name"
                    | "description"
                    | "personality"
                    | "scenario"
                    | "first_mes"
                    | "mes_example"
                    | "system_prompt"
                    | "post_history_instructions"
                    | "tags"
                    | "creator"
                    | "character_version"
                    | "alternate_greetings"
                    | "extensions"
                    | "character_book"
            ) {
                continue;
            }
            report.push(CompatFinding {
                area: "st.data.extra".into(),
                field_path: key.clone(),
                severity: CompatSeverity::Preserved,
                detail: "unknown ST data-level field retained via flatten extra/raw_card_json"
                    .into(),
                before: obj.get(key).cloned(),
                after: None,
            });
        }
    }

    if let Some(obj) = character.extensions.as_object() {
        for key in obj.keys() {
            report.push(CompatFinding {
                area: "extensions".into(),
                field_path: key.clone(),
                severity: CompatSeverity::Preserved,
                detail: "extension key retained opaquely".into(),
                before: obj.get(key).cloned(),
                after: None,
            });
        }
    }

    let scripts = character.scoped_regex_scripts();
    if !scripts.is_empty() {
        report.push(CompatFinding {
            area: "regex_scripts".into(),
            field_path: "extensions.regex_scripts".into(),
            severity: CompatSeverity::Preserved,
            detail: format!("{} scoped regex script(s) parsed", scripts.len()),
            before: None,
            after: None,
        });
    }

    let mvu = extract_mvu_schema_from_extensions(&character.extensions);
    if !mvu.is_empty() {
        report.push(CompatFinding {
            area: "mvu".into(),
            field_path: "extensions.stat_data|mvu.initvar|variables".into(),
            severity: CompatSeverity::Preserved,
            detail: format!("{} MVU/stat_data schema field(s) detected", mvu.len()),
            before: None,
            after: None,
        });
    }

    if let Some(book) = &character.embedded_world_info {
        report_world_book(&mut report, book);
    }

    report
}

fn report_world_book(report: &mut CompatReport, book: &WorldInfoBook) {
    report.push(CompatFinding {
        area: "character_book".into(),
        field_path: "entries".into(),
        severity: CompatSeverity::Preserved,
        detail: format!("{} world book entries imported", book.entries.len()),
        before: None,
        after: None,
    });
    if !book.metadata.is_empty() {
        for key in book.metadata.keys() {
            report.push(CompatFinding {
                area: "character_book.metadata".into(),
                field_path: key.clone(),
                severity: CompatSeverity::Preserved,
                detail: "book-level metadata retained".into(),
                before: book.metadata.get(key).cloned(),
                after: None,
            });
        }
    }
}

/// Compare a Character after import → export → re-import against the first import.
pub fn compare_character_roundtrip(original: &Character, roundtripped: &Character) -> CompatReport {
    let mut report = CompatReport::new("compare_character_roundtrip", None);

    // Intentional: new internal ids each import.
    if original.id != roundtripped.id {
        report.push(CompatFinding {
            area: "character".into(),
            field_path: "id".into(),
            severity: CompatSeverity::Intentional,
            detail: "Character.id is regenerated on every import".into(),
            before: Some(Value::String(original.id.as_str().to_string())),
            after: Some(Value::String(roundtripped.id.as_str().to_string())),
        });
    }

    for (path, left, right) in [
        ("name", original.name.as_str(), roundtripped.name.as_str()),
        (
            "description",
            original.description.as_str(),
            roundtripped.description.as_str(),
        ),
        (
            "personality",
            original.personality.as_str(),
            roundtripped.personality.as_str(),
        ),
        (
            "scenario",
            original.scenario.as_str(),
            roundtripped.scenario.as_str(),
        ),
        (
            "first_mes",
            original.first_mes.as_str(),
            roundtripped.first_mes.as_str(),
        ),
        (
            "mes_example",
            original.mes_example.as_str(),
            roundtripped.mes_example.as_str(),
        ),
        (
            "system_prompt",
            original.system_prompt.as_str(),
            roundtripped.system_prompt.as_str(),
        ),
        (
            "post_history_instructions",
            original.post_history_instructions.as_str(),
            roundtripped.post_history_instructions.as_str(),
        ),
        (
            "creator",
            original.creator.as_str(),
            roundtripped.creator.as_str(),
        ),
        (
            "character_version",
            original.character_version.as_str(),
            roundtripped.character_version.as_str(),
        ),
        (
            "spec_version",
            original.spec_version.as_str(),
            roundtripped.spec_version.as_str(),
        ),
    ] {
        if left != right {
            report.push(CompatFinding {
                area: "character".into(),
                field_path: path.into(),
                severity: CompatSeverity::Loss,
                detail: "typed field changed across round-trip".into(),
                before: Some(Value::String(left.to_string())),
                after: Some(Value::String(right.to_string())),
            });
        } else {
            report.push(CompatFinding {
                area: "character".into(),
                field_path: path.into(),
                severity: CompatSeverity::Preserved,
                detail: "typed field stable across round-trip".into(),
                before: None,
                after: None,
            });
        }
    }

    if original.tags != roundtripped.tags {
        report.push(CompatFinding {
            area: "character".into(),
            field_path: "tags".into(),
            severity: CompatSeverity::Loss,
            detail: "tags changed across round-trip".into(),
            before: Some(Value::Array(
                original
                    .tags
                    .iter()
                    .map(|t| Value::String(t.clone()))
                    .collect(),
            )),
            after: Some(Value::Array(
                roundtripped
                    .tags
                    .iter()
                    .map(|t| Value::String(t.clone()))
                    .collect(),
            )),
        });
    }

    if original.alternate_greetings != roundtripped.alternate_greetings {
        report.push(CompatFinding {
            area: "character".into(),
            field_path: "alternate_greetings".into(),
            severity: CompatSeverity::Loss,
            detail: "alternate_greetings changed across round-trip".into(),
            before: Some(Value::from(original.alternate_greetings.clone())),
            after: Some(Value::from(roundtripped.alternate_greetings.clone())),
        });
    }

    if original.extensions != roundtripped.extensions {
        // extensions may reorder object keys; compare canonical JSON.
        let left = canonicalize(&original.extensions);
        let right = canonicalize(&roundtripped.extensions);
        if left != right {
            report.push(CompatFinding {
                area: "extensions".into(),
                field_path: "extensions".into(),
                severity: CompatSeverity::Loss,
                detail: "extensions payload changed across round-trip".into(),
                before: Some(original.extensions.clone()),
                after: Some(roundtripped.extensions.clone()),
            });
        } else {
            report.push(CompatFinding {
                area: "extensions".into(),
                field_path: "extensions".into(),
                severity: CompatSeverity::Preserved,
                detail: "extensions payload stable (canonical)".into(),
                before: None,
                after: None,
            });
        }
    } else {
        report.push(CompatFinding {
            area: "extensions".into(),
            field_path: "extensions".into(),
            severity: CompatSeverity::Preserved,
            detail: "extensions payload stable".into(),
            before: None,
            after: None,
        });
    }

    // Unknown ST data-level fields via raw_card_json
    if let (Some(left), Some(right)) = (
        original.raw_card_json.as_object(),
        roundtripped.raw_card_json.as_object(),
    ) {
        for (key, value) in left {
            if is_known_st_data_key(key) {
                continue;
            }
            match right.get(key) {
                Some(after) if after == value => {
                    report.push(CompatFinding {
                        area: "st.data.extra".into(),
                        field_path: key.clone(),
                        severity: CompatSeverity::Preserved,
                        detail: "unknown data-level field survived round-trip".into(),
                        before: Some(value.clone()),
                        after: Some(after.clone()),
                    });
                }
                Some(after) => {
                    report.push(CompatFinding {
                        area: "st.data.extra".into(),
                        field_path: key.clone(),
                        severity: CompatSeverity::Loss,
                        detail: "unknown data-level field mutated".into(),
                        before: Some(value.clone()),
                        after: Some(after.clone()),
                    });
                }
                None => {
                    report.push(CompatFinding {
                        area: "st.data.extra".into(),
                        field_path: key.clone(),
                        severity: CompatSeverity::Loss,
                        detail: "unknown data-level field dropped".into(),
                        before: Some(value.clone()),
                        after: None,
                    });
                }
            }
        }
    }

    compare_regex_scripts(
        &mut report,
        &original.scoped_regex_scripts(),
        &roundtripped.scoped_regex_scripts(),
    );
    compare_world_books(
        &mut report,
        original.embedded_world_info.as_ref(),
        roundtripped.embedded_world_info.as_ref(),
    );

    // Wire-level `position` verdict. The former code pushed an unconditional
    // `Intentional` row here with no `before`/`after` evidence, which hid every
    // label ⇄ code transition from the gate. The actual representation change is
    // now read from the preserved raw ST JSON of both sides and classified
    // (`Normalized` under an explicit mapping, `WireDrift` otherwise).
    compare_wire_positions(
        &mut report,
        &original.raw_card_json,
        &roundtripped.raw_card_json,
    );

    report
}

fn compare_regex_scripts(report: &mut CompatReport, left: &[RegexScript], right: &[RegexScript]) {
    if left.len() != right.len() {
        report.push(CompatFinding {
            area: "regex_scripts".into(),
            field_path: "extensions.regex_scripts".into(),
            severity: CompatSeverity::Loss,
            detail: format!(
                "scoped regex count changed: {} -> {}",
                left.len(),
                right.len()
            ),
            before: Some(Value::from(left.len() as u64)),
            after: Some(Value::from(right.len() as u64)),
        });
        return;
    }
    for (idx, (a, b)) in left.iter().zip(right.iter()).enumerate() {
        if a.id != b.id
            || a.find_regex != b.find_regex
            || a.replace_string != b.replace_string
            || a.placement_codes != b.placement_codes
            || a.markdown_only != b.markdown_only
            || a.prompt_only != b.prompt_only
            || a.run_on_edit != b.run_on_edit
            || a.substitute_regex != b.substitute_regex
            || a.trim_strings != b.trim_strings
            || a.min_depth != b.min_depth
            || a.max_depth != b.max_depth
        {
            report.push(CompatFinding {
                area: "regex_scripts".into(),
                field_path: format!("extensions.regex_scripts[{idx}]"),
                severity: CompatSeverity::Loss,
                detail: "scoped regex metadata changed".into(),
                before: Some(serde_json::json!({
                    "id": a.id,
                    "find": a.find_regex,
                    "replace": a.replace_string,
                    "placement": a.placement_codes,
                })),
                after: Some(serde_json::json!({
                    "id": b.id,
                    "find": b.find_regex,
                    "replace": b.replace_string,
                    "placement": b.placement_codes,
                })),
            });
        } else {
            report.push(CompatFinding {
                area: "regex_scripts".into(),
                field_path: format!("extensions.regex_scripts[{idx}]"),
                severity: CompatSeverity::Preserved,
                detail: "scoped regex metadata stable".into(),
                before: None,
                after: None,
            });
        }
    }
}

fn compare_world_books(
    report: &mut CompatReport,
    left: Option<&WorldInfoBook>,
    right: Option<&WorldInfoBook>,
) {
    match (left, right) {
        (None, None) => {}
        (Some(_), None) => {
            report.push(CompatFinding {
                area: "character_book".into(),
                field_path: "character_book".into(),
                severity: CompatSeverity::Loss,
                detail: "embedded world book dropped".into(),
                before: None,
                after: None,
            });
        }
        (None, Some(_)) => {
            report.push(CompatFinding {
                area: "character_book".into(),
                field_path: "character_book".into(),
                severity: CompatSeverity::Loss,
                detail: "embedded world book unexpectedly appeared".into(),
                before: None,
                after: None,
            });
        }
        (Some(a), Some(b)) => {
            if a.metadata != b.metadata {
                report.push(CompatFinding {
                    area: "character_book.metadata".into(),
                    field_path: "character_book.extra".into(),
                    severity: CompatSeverity::Loss,
                    detail: "book-level metadata changed or dropped".into(),
                    before: Some(Value::Object(a.metadata.clone().into_iter().collect())),
                    after: Some(Value::Object(b.metadata.clone().into_iter().collect())),
                });
            } else if !a.metadata.is_empty() {
                report.push(CompatFinding {
                    area: "character_book.metadata".into(),
                    field_path: "character_book.extra".into(),
                    severity: CompatSeverity::Preserved,
                    detail: "book-level metadata stable".into(),
                    before: None,
                    after: None,
                });
            }

            if a.entries.len() != b.entries.len() {
                report.push(CompatFinding {
                    area: "character_book".into(),
                    field_path: "entries".into(),
                    severity: CompatSeverity::Loss,
                    detail: format!(
                        "world book entry count changed: {} -> {}",
                        a.entries.len(),
                        b.entries.len()
                    ),
                    before: Some(Value::from(a.entries.len() as u64)),
                    after: Some(Value::from(b.entries.len() as u64)),
                });
                return;
            }

            for (idx, (le, re)) in a.entries.iter().zip(b.entries.iter()).enumerate() {
                // Entry-level `extra` (unknown ST fields such as `insertion_order`,
                // `case_sensitive`, `group`, `probability`) is exactly what this
                // crate claims to preserve, so it is part of the entry verdict.
                let mut entry_loss = le.keys != re.keys
                    || le.secondary_keys != re.secondary_keys
                    || le.content != re.content
                    || le.constant != re.constant
                    || le.selective != re.selective
                    || le.selective_logic != re.selective_logic
                    || le.order != re.order
                    || le.depth != re.depth
                    || le.st_id != re.st_id
                    || canonicalize(&le.extensions) != canonicalize(&re.extensions)
                    || le.extra != re.extra;
                // Both sides are already-normalized internal codes here, so a
                // difference is a real injection-position change: it is counted
                // as an entry loss (the wire label ⇄ code verdict is produced by
                // `compare_wire_positions` and by the wire comparison leg).
                if le.position != re.position {
                    entry_loss = true;
                }
                if entry_loss {
                    report.push(CompatFinding {
                        area: "character_book.entry".into(),
                        field_path: format!("entries[{idx}]"),
                        severity: CompatSeverity::Loss,
                        detail: "world book entry fields changed".into(),
                        before: Some(serde_json::json!({
                            "keys": le.keys,
                            "secondary_keys": le.secondary_keys,
                            "content": le.content,
                            "constant": le.constant,
                            "selective": le.selective,
                            "order": le.order,
                            "depth": le.depth,
                            "position": le.position,
                            "st_id": le.st_id,
                            "extra": le.extra,
                        })),
                        after: Some(serde_json::json!({
                            "keys": re.keys,
                            "secondary_keys": re.secondary_keys,
                            "content": re.content,
                            "constant": re.constant,
                            "selective": re.selective,
                            "order": re.order,
                            "depth": re.depth,
                            "position": re.position,
                            "st_id": re.st_id,
                            "extra": re.extra,
                        })),
                    });
                } else {
                    report.push(CompatFinding {
                        area: "character_book.entry".into(),
                        field_path: format!("entries[{idx}]"),
                        severity: CompatSeverity::Preserved,
                        detail: "world book entry stable".into(),
                        before: None,
                        after: None,
                    });
                }
            }
        }
    }
}

fn is_known_st_data_key(key: &str) -> bool {
    matches!(
        key,
        "name"
            | "description"
            | "personality"
            | "scenario"
            | "first_mes"
            | "mes_example"
            | "system_prompt"
            | "post_history_instructions"
            | "tags"
            | "creator"
            | "character_version"
            | "alternate_greetings"
            | "extensions"
            | "character_book"
    )
}

fn canonicalize(value: &Value) -> Value {
    match value {
        Value::Object(map) => {
            let mut keys: Vec<_> = map.keys().cloned().collect();
            keys.sort();
            let mut out = serde_json::Map::new();
            for key in keys {
                if let Some(v) = map.get(&key) {
                    out.insert(key, canonicalize(v));
                }
            }
            Value::Object(out)
        }
        Value::Array(items) => Value::Array(items.iter().map(canonicalize).collect()),
        other => other.clone(),
    }
}

fn path_is_intentional(path: &str, full: &str, intentional_paths: &[&str]) -> bool {
    intentional_paths.iter().any(|p| {
        *p == path
            || full == *p
            || full.ends_with(&format!(".{p}"))
            || path.ends_with(&format!(".{p}"))
    })
}

/// Explicit ST `position` wire mapping: v2/v3 string labels ⇄ StoryForge's
/// internal numeric code.
///
/// The numeric side is pinned to the domain source of truth
/// [`storyforge_domain::character::StWorldInfoEntry::position_as_i32`]
/// (crates/domain/src/character.rs:153) by
/// `position_wire_mapping_matches_domain_mapping`. The table exists because
/// that function folds *unknown* labels into `0`, which would otherwise make an
/// unknown label look equivalent to `before_char`.
const POSITION_WIRE_MAPPING: &[(&str, i64)] = &[
    ("before_char", 0),
    ("after_char", 1),
    ("in_roleplay", 2),
    ("before_examples", 3),
    ("after_examples", 4),
];

/// Code reference for the `position` label ⇄ code equivalence.
const POSITION_MAPPING_REFERENCE: &str = "storyforge_domain::character::StWorldInfoEntry::position_as_i32 (crates/domain/src/character.rs:153)";

/// Last dotted segment of a comparison path (`entries[3].position` → `position`).
fn leaf_key(path: &str) -> &str {
    let leaf = path.rsplit('.').next().unwrap_or(path);
    leaf.split('[').next().unwrap_or(leaf)
}

fn position_label_matches_code(label: &str, code: Option<i64>) -> bool {
    match code {
        Some(code) => POSITION_WIRE_MAPPING
            .iter()
            .any(|(known_label, known_code)| *known_label == label && *known_code == code),
        None => false,
    }
}

/// Evidence-based verdict for a wire-level `position` change.
///
/// ST v2/v3 cards declare `position` as a string label, while StoryForge's
/// export path writes the internal numeric code, so a label ⇄ code transition is
/// a **wire-contract** change. It is reported as `Normalized` (still
/// non-`Intentional`, with `before`/`after` evidence) only when the two values
/// are equivalent under [`POSITION_WIRE_MAPPING`]; every other change — unknown
/// label, unmapped code, or an unrelated value — is a hard `WireDrift`.
fn classify_wire_position_change(before: &Value, after: &Value) -> (CompatSeverity, String) {
    let equivalent = match (before, after) {
        (Value::String(label), Value::Number(code))
        | (Value::Number(code), Value::String(label)) => {
            position_label_matches_code(label, code.as_i64())
        }
        _ => false,
    };
    if equivalent {
        (
            CompatSeverity::Normalized,
            format!(
                "position wire type changed (string label ⇄ numeric code); values are equivalent under {POSITION_MAPPING_REFERENCE}, but the ST card spec declares a string so third-party consumers see a type change"
            ),
        )
    } else {
        (
            CompatSeverity::WireDrift,
            "position wire value changed with no declared equivalence mapping".into(),
        )
    }
}

/// Wire-level verdict for a changed `position` leaf, or `None` for any other path.
fn classify_wire_change(
    path: &str,
    before: &Value,
    after: &Value,
) -> Option<(CompatSeverity, String)> {
    if leaf_key(path) != "position" {
        return None;
    }
    Some(classify_wire_position_change(before, after))
}

/// Raw (wire) `position` values in book order from a preserved ST `data` JSON.
fn wire_positions(data: &Value) -> Vec<Value> {
    data.get("character_book")
        .and_then(|book| book.get("entries"))
        .and_then(Value::as_array)
        .map(|entries| {
            entries
                .iter()
                .map(|entry| entry.get("position").cloned().unwrap_or(Value::Null))
                .collect()
        })
        .unwrap_or_default()
}

/// Evidence-based wire-level `position` verdict between two preserved raw ST
/// JSON payloads.
///
/// Replaces the former blanket "position string → number is intentional"
/// finding in [`compare_character_roundtrip`]: the actual representation change
/// is read from the preserved wire JSON of both sides and classified per entry.
fn compare_wire_positions(report: &mut CompatReport, left_data: &Value, right_data: &Value) {
    let left = wire_positions(left_data);
    let right = wire_positions(right_data);
    for (idx, (before, after)) in left.iter().zip(right.iter()).enumerate() {
        if before == after {
            continue;
        }
        let (severity, detail) = classify_wire_position_change(before, after);
        report.push(CompatFinding {
            area: "character_book.entry".into(),
            field_path: format!("entries[{idx}].position"),
            severity,
            detail,
            before: Some(before.clone()),
            after: Some(after.clone()),
        });
    }
}

fn compare_value(
    area: &str,
    path: &str,
    before: &Value,
    after: &Value,
    intentional_paths: &[&str],
    out: &mut Vec<CompatFinding>,
) {
    let full = if path.is_empty() {
        area.to_string()
    } else {
        format!("{area}.{path}")
    };
    if path_is_intentional(path, &full, intentional_paths) {
        if before != after {
            out.push(CompatFinding {
                area: area.into(),
                field_path: path.into(),
                severity: CompatSeverity::Intentional,
                detail: "listed intentional normalization path".into(),
                before: Some(before.clone()),
                after: Some(after.clone()),
            });
        }
        return;
    }

    match (before, after) {
        (Value::Object(a), Value::Object(b)) => {
            for (key, av) in a {
                let child = if path.is_empty() {
                    key.clone()
                } else {
                    format!("{path}.{key}")
                };
                let child_full = format!("{area}.{child}");
                match b.get(key) {
                    Some(bv) => compare_value(area, &child, av, bv, intentional_paths, out),
                    None if path_is_intentional(&child, &child_full, intentional_paths) => {
                        out.push(CompatFinding {
                            area: area.into(),
                            field_path: child,
                            severity: CompatSeverity::Intentional,
                            detail: "listed intentional normalization path dropped/normalized"
                                .into(),
                            before: Some(av.clone()),
                            after: None,
                        });
                    }
                    None => out.push(CompatFinding {
                        area: area.into(),
                        field_path: child,
                        severity: CompatSeverity::Loss,
                        detail: "object field dropped".into(),
                        before: Some(av.clone()),
                        after: None,
                    }),
                }
            }
            for (key, bv) in b {
                if !a.contains_key(key) {
                    let child = if path.is_empty() {
                        key.clone()
                    } else {
                        format!("{path}.{key}")
                    };
                    out.push(CompatFinding {
                        area: area.into(),
                        field_path: child,
                        severity: CompatSeverity::Intentional,
                        detail: "object field added during export/import".into(),
                        before: None,
                        after: Some(bv.clone()),
                    });
                }
            }
        }
        (Value::Array(a), Value::Array(b)) => {
            if a.len() != b.len() {
                out.push(CompatFinding {
                    area: area.into(),
                    field_path: path.into(),
                    severity: CompatSeverity::Loss,
                    detail: format!("array length changed: {} -> {}", a.len(), b.len()),
                    before: Some(before.clone()),
                    after: Some(after.clone()),
                });
                return;
            }
            for (i, (av, bv)) in a.iter().zip(b.iter()).enumerate() {
                let child = format!("{path}[{i}]");
                compare_value(area, &child, av, bv, intentional_paths, out);
            }
        }
        (a, b) if a == b => {
            out.push(CompatFinding {
                area: area.into(),
                field_path: path.into(),
                severity: CompatSeverity::Preserved,
                detail: "value stable".into(),
                before: None,
                after: None,
            });
        }
        (a, b) => {
            // A changed wire value is judged on evidence: a `position` change is
            // classified as `Normalized` (explicit mapping) or `WireDrift`, every
            // other value change stays a `Loss`.
            let (severity, detail) = classify_wire_change(path, a, b)
                .unwrap_or((CompatSeverity::Loss, "value changed".into()));
            out.push(CompatFinding {
                area: area.into(),
                field_path: path.into(),
                severity,
                detail,
                before: Some(a.clone()),
                after: Some(b.clone()),
            });
        }
    }
}

