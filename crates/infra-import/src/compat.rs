        write_real_card_evidence(&evidence, &path).expect("write evidence");
        let on_disk = std::fs::read_to_string(&path).unwrap();
        assert!(on_disk.contains("raw_card_json_sha256"));
        assert!(!on_disk.contains("secret lore"));
