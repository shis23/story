/// Deterministic pseudo-random for bounded property tests (xorshift64*).
#[derive(Debug, Clone)]
pub struct SeedRng {
    state: u64,
}

impl SeedRng {
    pub fn new(seed: u64) -> Self {
        Self {
            state: if seed == 0 {
                0x9E37_79B9_7F4A_7C15
            } else {
                seed
            },
        }
    }

    pub fn next_u64(&mut self) -> u64 {
        let mut x = self.state;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.state = x;
        x.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }

    pub fn next_usize(&mut self, max: usize) -> usize {
        if max == 0 {
            return 0;
        }
        (self.next_u64() as usize) % max
    }

    pub fn next_bool(&mut self) -> bool {
        self.next_u64() & 1 == 1
    }

    pub fn next_string(&mut self, max_len: usize) -> String {
        const ALPHABET: &[u8] =
            b"abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-<>/";
        let len = self.next_usize(max_len.saturating_add(1));
        (0..len)
            .map(|_| ALPHABET[self.next_usize(ALPHABET.len())] as char)
            .collect()
    }
}

/// Generate a minimal hostile-but-bounded ST card JSON for property tests.
pub fn generate_edge_card_json(rng: &mut SeedRng) -> Value {
    let name = format!("fuzz-{}", rng.next_string(12));
    let alt_count = rng.next_usize(4);
    let mut alternate_greetings = Vec::new();
    for _ in 0..alt_count {
        alternate_greetings.push(Value::String(rng.next_string(48)));
    }

    let entry_count = rng.next_usize(5);
    let mut entries = Vec::new();
    for i in 0..entry_count {
        // Never emit empty secondary_keys arrays: first-import normalizes
        // empty → null, which is intentional but noisy in strict compares.
        // Prefer either a non-empty list or omit the field entirely.
        let mut entry = serde_json::json!({
            "id": i as i32,
            "keys": [rng.next_string(8), rng.next_string(8)],
            "content": rng.next_string(64),
            "constant": rng.next_bool(),
            "selective": rng.next_bool(),
            "selective_logic": rng.next_usize(3) as i32,
            "position": if rng.next_bool() { Value::String("after_char".into()) } else { Value::from(1) },
            "order": rng.next_usize(200) as i32,
            "depth": rng.next_usize(8) as i32,
            "extensions": {
                "entry_extra": { "seed": rng.next_u64() }
            }
        });
        if rng.next_bool() {
            entry.as_object_mut().unwrap().insert(
                "secondary_keys".into(),
                serde_json::json!([rng.next_string(6)]),
            );
        }
        entries.push(entry);
    }

    let hostile_regex = if rng.next_bool() {
        r#"(?s)<script>.*?</script>"#
    } else {
        r#"/<img[^>]*>/gi"#
    };

    serde_json::json!({
        "spec": "chara_card_v2",
        "spec_version": if rng.next_bool() { "3.0" } else { "2.0" },
        "data": {
            "name": name,
            "description": rng.next_string(80),
            "personality": rng.next_string(40),
            "scenario": rng.next_string(40),
            "first_mes": rng.next_string(40),
            "mes_example": rng.next_string(20),
            "system_prompt": rng.next_string(30),
            "post_history_instructions": rng.next_string(20),
            "tags": [rng.next_string(8), "fuzz"],
            "creator": "compat-fuzz",
            "character_version": format!("{}", rng.next_usize(9)),
            "alternate_greetings": alternate_greetings,
            "group_only": rng.next_bool(),
            "creator_notes": rng.next_string(24),
            "extensions": {
                "unknown_plugin": { "flag": rng.next_bool(), "n": rng.next_u64() },
                "stat_data": { "hp": rng.next_usize(200) as i64, "mood": rng.next_string(8) },
                "regex_scripts": [{
                    "id": format!("fuzz-{}", rng.next_string(6)),
                    "scriptName": "Hostile cleanup",
                    "findRegex": hostile_regex,
                    "replaceString": "",
                    "placement": [1, 2],
                    "disabled": false,
                    "markdownOnly": rng.next_bool(),
                    "promptOnly": rng.next_bool()
                }]
            },
            "character_book": {
                "name": format!("book-{}", rng.next_string(6)),
                "description": rng.next_string(20),
                "scan_depth": rng.next_usize(20) as i32,
                "extensions": { "book_plugin": { "on": true } },
                "entries": entries
            }
        }
    })
}

/// Generate a sanitized large-worldbook ST card for property testing.
///
/// Deterministic from `rng`. Covers constant/selective/both routes, legacy
/// `key`/`keysecondary` aliases, numeric and string positions, entry
/// `extensions`, and a few `disable: true` entries (which are intentionally
/// filtered on import).
pub fn generate_large_worldbook_card(rng: &mut SeedRng) -> Value {
    let active = 40 + rng.next_usize(20);
    let disabled = 1 + rng.next_usize(4);
    let mut entries = Vec::new();
    let mut id = 0i32;
    for _ in 0..active {
        let route = rng.next_usize(3);
        let mut entry = serde_json::json!({
            "id": id,
            "content": rng.next_string(48),
            "order": id,
            "extensions": { "entry_extra": { "rank": id } }
        });
        let entry_obj = entry.as_object_mut().unwrap();
        match route {
            0 => {
                entry_obj.insert("constant".into(), Value::Bool(true));
                entry_obj.insert(
                    "position".into(),
                    if rng.next_bool() {
                        Value::String("before_char".into())
                    } else {
                        Value::from(0)
                    },
                );
            }
            1 => {
                entry_obj.insert("selective".into(), Value::Bool(true));
                entry_obj.insert(
                    "selective_logic".into(),
                    Value::from(rng.next_usize(3) as i64),
                );
                entry_obj.insert("depth".into(), Value::from(rng.next_usize(8) as i64));
                entry_obj.insert(
                    "position".into(),
                    if rng.next_bool() {
                        Value::String("after_char".into())
                    } else {
                        Value::from(1)
                    },
                );
            }
            _ => {
                entry_obj.insert("constant".into(), Value::Bool(true));
                entry_obj.insert("selective".into(), Value::Bool(true));
                entry_obj.insert("position".into(), Value::from(rng.next_usize(5) as i64));
            }
        }
        if rng.next_bool() {
            entry_obj.insert("key".into(), serde_json::json!([rng.next_string(6)]));
            entry_obj.insert("keysecondary".into(), Value::String(rng.next_string(10)));
        } else {
            entry_obj.insert("keys".into(), serde_json::json!([rng.next_string(6)]));
            entry_obj.insert(
                "secondary_keys".into(),
                serde_json::json!([rng.next_string(6)]),
            );
        }
        entries.push(entry);
        id += 1;
    }
    for _ in 0..disabled {
        entries.push(serde_json::json!({
            "id": id + 10000,
            "disable": true,
            "keys": [rng.next_string(6)],
            "content": rng.next_string(16),
            "selective": true,
            "position": 0,
            "order": 0
        }));
        id += 1;
    }

    serde_json::json!({
        "spec": "chara_card_v2",
        "spec_version": if rng.next_bool() { "3.0" } else { "2.0" },
        "data": {
            "name": format!("large-{}", rng.next_string(8)),
            "description": rng.next_string(40),
            "personality": rng.next_string(20),
            "scenario": rng.next_string(20),
            "first_mes": rng.next_string(24),
            "tags": [rng.next_string(6), "large-book"],
            "creator": "compat-large",
            "character_version": format!("{}", rng.next_usize(9)),
            "alternate_greetings": (0..rng.next_usize(3)).map(|_| Value::String(rng.next_string(24))).collect::<Vec<_>>(),
            "extensions": {
                "depth_prompt": { "depth": rng.next_usize(8) as i64, "prompt": rng.next_string(16) },
                "unknown_plugin": { "flag": rng.next_bool() }
            },
            "character_book": {
                "name": rng.next_string(8),
                "description": rng.next_string(16),
                "scan_depth": rng.next_usize(20) as i64,
                "extensions": { "book_plugin": { "on": true } },
                "entries": entries
            }
        }
    })
}

/// Generate a sanitized reasoning/regex ST card for property testing.
///
/// Deterministic from `rng`. Covers Reasoning (placement 6), Input (1),
/// Output (2) regex scripts with minDepth/maxDepth, markdownOnly/promptOnly.
pub fn generate_reasoning_regex_card(rng: &mut SeedRng) -> Value {
    let script_count = 1 + rng.next_usize(3);
    let mut scripts = Vec::new();
    let placements = [6i32, 1, 2, 5];
    for i in 0..script_count {
        let placement = placements[rng.next_usize(placements.len())];
        let mut script = serde_json::json!({
            "id": format!("reasoning-{}-{}", i, rng.next_string(4)),
            "scriptName": rng.next_string(10),
            "findRegex": format!("/{}/g", rng.next_string(12)),
            "replaceString": rng.next_string(6),
            "placement": [placement],
            "disabled": false
        });
        let obj = script.as_object_mut().unwrap();
        if rng.next_bool() {
            obj.insert("promptOnly".into(), Value::Bool(rng.next_bool()));
        }
        if rng.next_bool() {
            obj.insert("markdownOnly".into(), Value::Bool(rng.next_bool()));
        }
        if rng.next_bool() {
            obj.insert("minDepth".into(), Value::from(rng.next_usize(5) as i64));
            obj.insert("maxDepth".into(), Value::from(rng.next_usize(10) as i64));
        }
        scripts.push(script);
    }

    serde_json::json!({
        "spec": "chara_card_v2",
        "spec_version": "3.0",
        "data": {
            "name": format!("reasoning-{}", rng.next_string(8)),
            "description": rng.next_string(40),
            "first_mes": rng.next_string(24),
            "tags": ["reasoning", "regex"],
            "creator": "compat-reasoning",
            "alternate_greetings": [rng.next_string(20)],
            "extensions": {
                "depth_prompt": { "depth": rng.next_usize(6) as i64, "prompt": rng.next_string(16) },
                "regex_scripts": scripts,
                "fav": rng.next_bool()
            }
        }
    })
}

