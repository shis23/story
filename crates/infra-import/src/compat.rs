    #[test]
    fn bounded_property_suite_roundtrips_without_loss() {
        const SEED: u64 = 0xC0A7_5EED;
        let mut rng = SeedRng::new(SEED);
        let mut aggregate = CompatReport::new("bounded_property_suite", Some(SEED));
        for i in 0..24 {
            let card = generate_edge_card_json(&mut rng);
            let bytes = serde_json::to_vec(&card).unwrap();
            let imported = import_character_from_json(&bytes)
                .unwrap_or_else(|e| panic!("seed={SEED} case={i} import failed: {e}"));
            let exported = to_st_data(
                &imported,
                None,
                imported
                    .embedded_world_info
                    .as_ref()
                    .map(|b| b.to_st_book()),
            );
            let st_card = png::make_st_card(exported, &imported.spec_version);
            let png_bytes = png::write_st_card_png(&st_card, None)
                .unwrap_or_else(|e| panic!("seed={SEED} case={i} png export failed: {e}"));
            let round = import_character(&png_bytes)
                .unwrap_or_else(|e| panic!("seed={SEED} case={i} reimport failed: {e}"));
            let report = compare_character_roundtrip(&imported, &round);
            if report.has_losses() {
                panic!(
                    "seed={SEED} case={i} losses:\n{}",
                    report.to_json_pretty().unwrap()
                );
            }
            for finding in report.findings {
                aggregate.push(finding);
            }
        }
        assert!(aggregate.summary.preserved > 0);
        assert_eq!(aggregate.summary.loss, 0);
    }
